    fun getSkillsByCategory(
        category: String?
    ): List<SkillEntity> {

        return when (category) {

            BusinessCategory.CAFE ->
                cafeSkills

            BusinessCategory.RESTAURANT ->
                restaurantSkills

            BusinessCategory.CONVENIENCE_STORE ->
                convenienceStoreSkills

            BusinessCategory.RETAIL_SHOP ->
                retailSkills

            BusinessCategory.WAREHOUSE ->
                warehouseSkills

            BusinessCategory.OFFICE ->
                officeSkills

            BusinessCategory.EVENT_AGENCY ->
                eventSkills

            BusinessCategory.ENTERTAINMENT ->
                entertainmentSkills

            BusinessCategory.TUTOR_CENTER ->
                tutorCenterSkills

            else ->
                emptyList()
        }
    }

    fun getAllSkills(): List<SkillEntity> {

