package com.studentjobs.app.data.model.job

import java.util.Date

data class ShiftEntity(

    // ========================================
    // ID
    // ========================================

    val shiftId: String = "",

    // ========================================
    // RELATION
    // ========================================

    val jobId: String = "",

    // ========================================
    // SHIFT
    // ========================================

    // 1 = Monday
    // ...
    // 7 = Sunday

    val dayOfWeek: Int = 1,

    // ========================================
    // TIME
    // ========================================

    // minutes from 00:00

    val startMinute: Int = 0,

    val endMinute: Int = 0,

    // ========================================
    // STATUS
    // ========================================

    val status: String = "ACTIVE",

    // ========================================
    // SYSTEM
    // ========================================
    val createdAt: Date? = null
)